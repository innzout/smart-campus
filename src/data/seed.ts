/**
 * The JSON files are the database of record, generated by `scripts/seed.mjs`.
 *
 * A deployed demo is built once but shown for weeks, so every date is shifted
 * forward at load time. The shift is a whole number of **weeks**: that keeps
 * each record on the same weekday, so attendance never lands on a Sunday and
 * the timetable still lines up. Drift is therefore at most six days.
 */

const DAY_MS = 86_400_000;

const startOfDay = (d: Date) => new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();

function parseISO(iso: string) {
  const [y, m, d] = iso.slice(0, 10).split('-').map(Number);
  return new Date(y!, m! - 1, d!);
}

const toISO = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

/** Whole weeks between the seed date and today, never negative. */
function weekShiftDays(seededOn: string): number {
  const days = Math.round((startOfDay(new Date()) - startOfDay(parseISO(seededOn))) / DAY_MS);
  return days <= 0 ? 0 : Math.floor(days / 7) * 7;
}

/** Shift a `YYYY-MM-DD` or `YYYY-MM-DDTHH:mm:ss` value, preserving any time part. */
function shift(value: string, days: number): string {
  const d = parseISO(value);
  d.setDate(d.getDate() + days);
  return value.length > 10 ? `${toISO(d)}${value.slice(10)}` : toISO(d);
}

/** Every date-bearing field, by collection. */
const DATE_FIELDS: Partial<Record<keyof Database, string[]>> = {
  users: ['joinedOn'],
  attendance: ['date'],
  homework: ['assignedOn', 'dueOn'],
  homeworkStatus: ['submittedOn'],
  exams: ['startsOn', 'endsOn'],
  fees: ['dueOn'],
  payments: ['paidOn'],
  circulars: ['postedOn'],
  events: ['date'],
  requests: ['createdOn'],
  loans: ['borrowedOn', 'dueOn', 'returnedOn'],
  notifications: ['createdOn'],
  meetingSlots: ['date'],
  meetingBookings: ['bookedOn'],
  visits: ['date'],
};

function rebase(db: Database): Database {
  const days = weekShiftDays(db.school[0]?.seededOn ?? toISO(new Date()));
  if (days === 0) return db;

  for (const [collection, fields] of Object.entries(DATE_FIELDS)) {
    const rows = db[collection as keyof Database] as unknown as Record<string, unknown>[];
    if (!Array.isArray(rows)) continue;
    for (const row of rows) {
      for (const field of fields!) {
        const value = row[field];
        if (typeof value === 'string' && value) row[field] = shift(value, days);
      }
    }
  }

  // Help-desk updates carry their own dates.
  for (const r of db.requests) {
    for (const u of r.updates) u.on = shift(u.on, days);
  }

  // Library fines follow from how overdue a loan is, so recompute them.
  const today = toISO(new Date());
  for (const loan of db.loans) {
    if (loan.returnedOn) {
      loan.fine = 0;
      continue;
    }
    const overdueDays = Math.round((startOfDay(parseISO(today)) - startOfDay(parseISO(loan.dueOn))) / DAY_MS);
    loan.fine = overdueDays > 0 ? overdueDays * 2 : 0;
  }

  // An exam is published once it has been sat.
  for (const exam of db.exams) exam.published = exam.endsOn < today;

  // The term follows the calendar: June–Sept 1, Oct–Dec 2, Jan–May 3.
  const month = new Date().getMonth();
  const term = month >= 5 && month <= 8 ? 1 : month >= 9 && month <= 11 ? 2 : 3;
  if (db.school[0]) db.school[0].currentTerm = term as 1 | 2 | 3;

  return db;
}

export const seedDatabase = (): Database =>
  rebase(
    structuredClone({
      school,
      classes,
      subjects,
      users,
      attendance,
      timetable,
      homework,
      homeworkStatus,
      exams,
      marks,
      fees,
      payments,
      circulars,
      events,
      requests,
      routes,
      studentTransport,
      books,
      loans,
      notifications,
      places,
      meetingSlots,
      meetingBookings,
      visits,
    }) as unknown as Database,
  );
